-- -----------------------------------------------------------------------------
-- 2. REUSABLE TRIGGER FUNCTION FOR updated_at
-- Emulates MySQL's ON UPDATE CURRENT_TIMESTAMP behavior faithfully.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

