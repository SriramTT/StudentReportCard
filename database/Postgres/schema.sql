-- =============================================================================
-- TABLE 8: class_subjects
-- Academic-year configuration linking classes/sections to subjects.
-- subject_name_snapshot preserves the historical subject name for reports.
--
-- Functional uniqueness with COALESCE(section_id, 0) prevents duplicate
-- configurations for both section-specific and class-wide configurations.
-- =============================================================================
CREATE TABLE class_subjects (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id        BIGINT          NOT NULL,
    class_id                BIGINT          NOT NULL,
    section_id              BIGINT          NULL,
    subject_id              BIGINT          NOT NULL,
    subject_name_snapshot   VARCHAR(150)    NOT NULL,
    is_active               BOOLEAN         NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMPTZ     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_class_subjects_academic_year
        FOREIGN KEY (academic_year_id) REFERENCES academic_years (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_class_subjects_class
        FOREIGN KEY (class_id) REFERENCES classes (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_class_subjects_section
        FOREIGN KEY (section_id) REFERENCES sections (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_class_subjects_subject
        FOREIGN KEY (subject_id) REFERENCES subjects (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- Functional UNIQUE index for nullable section_id
CREATE UNIQUE INDEX uk_class_subjects_config
    ON class_subjects (academic_year_id, class_id, (COALESCE(section_id, 0)), subject_id);

CREATE INDEX idx_class_subjects_academic_year_id ON class_subjects (academic_year_id);
