-- =============================================================================
-- TABLE 22: generated_reports
-- Historical PDF report records. PDFs are NEVER overwritten.
-- Revision identity uniqueness prevents duplicate revision numbers for the same context.
-- =============================================================================
CREATE TABLE generated_reports (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_academic_record_id  BIGINT              NOT NULL,
    report_type                 report_type_enum    NOT NULL,
    term_id                     BIGINT              NULL,
    assessment_id               BIGINT              NULL,
    revision_number             INTEGER             NOT NULL DEFAULT 1,
    file_path                   VARCHAR(500)        NOT NULL,
    generated_by_user_id        BIGINT              NOT NULL,
    generated_at                TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_gr_academic_record
        FOREIGN KEY (student_academic_record_id) REFERENCES student_academic_records (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_gr_term
        FOREIGN KEY (term_id) REFERENCES terms (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_gr_assessment
        FOREIGN KEY (assessment_id) REFERENCES assessments (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_gr_generated_by
        FOREIGN KEY (generated_by_user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- Functional UNIQUE index for revision identity with nullable term_id & assessment_id
CREATE UNIQUE INDEX uk_gr_revision_identity
    ON generated_reports (
        student_academic_record_id,
        report_type,
        (COALESCE(term_id, 0)),
        (COALESCE(assessment_id, 0)),
        revision_number
    );

CREATE INDEX idx_gr_student_academic_record_id ON generated_reports (student_academic_record_id);
CREATE INDEX idx_gr_term_id ON generated_reports (term_id);
CREATE INDEX idx_gr_assessment_id ON generated_reports (assessment_id);
CREATE INDEX idx_gr_generated_by_user_id ON generated_reports (generated_by_user_id);

